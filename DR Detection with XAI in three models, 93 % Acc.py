"""## ****1. Building an EfficientNetB3 Model on Gaussian Filtered 224x224 Images****

### Model Construction and Initial Training

We build a convolutional neural network using EfficientNetB3 as the base model with pretrained ImageNet weights.  
The base model is frozen to retain learned features while training a custom classifier head with dense and dropout layers for binary classification.  
The model is compiled with Adam optimizer, binary cross-entropy loss, and evaluation metrics including accuracy and AUC for robust performance measurement.  
Training proceeds for 10 epochs with early stopping and learning rate reduction callbacks to prevent overfitting and optimize convergence.
"""

# Build Model
base_model = EfficientNetB3(include_top=False, input_shape=(300,300,3), pooling='avg', weights='imagenet')
base_model.trainable = False

x = base_model.output
x = layers.Dense(128, activation='relu')(x)
x = layers.Dropout(0.4)(x)
output = layers.Dense(1, activation='sigmoid')(x)

model = Model(inputs=base_model.input, outputs=output)

# Compile
model.compile(
    optimizer=optimizers.Adam(learning_rate=1e-4),
    loss='binary_crossentropy',
    metrics=['accuracy',AUC(name='auc')]
)

# Callbacks
early_stop = EarlyStopping(patience=3, restore_best_weights=True)
lr_scheduler = ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=2, verbose=1)

# Initial training
history = model.fit(
    train_batches,
    epochs=10,
    validation_data=val_batches,
    callbacks=[early_stop, lr_scheduler]
)

# Fine-Tuning
base_model.trainable = True

# Freeze أول 100 طبقة
for layer in base_model.layers[:50]:
    layer.trainable = False

model.compile(
    optimizer=optimizers.Adam(1e-5),
    loss='binary_crossentropy',
    metrics=['accuracy' , AUC(name='auc')]
)

