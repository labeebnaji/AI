def preprocess_aptos_image_for_eval(image_base_dir, target_size=(300, 300)):
    """
    Preprocess APTOS image for evaluation: read, resize to target size, and convert to RGB.
    """
    img = cv2.imread(image_base_dir)
    if img is None:
        return None

    img_resized = cv2.resize(img, target_size)

    if len(img_resized.shape) == 2:
        img_resized = cv2.cvtColor(img_resized, cv2.COLOR_GRAY2RGB)
    elif img_resized.shape[2] == 4:
        img_resized = cv2.cvtColor(img_resized, cv2.COLOR_BGRA2BGR)

    return img_resized

